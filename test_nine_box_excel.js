const assert = require('node:assert/strict');
const ExcelJS = require('./nine-box-app/vendor/exceljs.min.js');
const {parseNineBoxExcel} = require('./nine-box-app/excel-import.js');
const book = new ExcelJS.Workbook();
const sheet = book.addWorksheet('ปี 71');
sheet.getCell('F3').value = 'วงเงินดำเนินการปี 2571';
sheet.getCell('A6').value = 'PRJ-2569-00001';
sheet.getCell('C6').value = 'TEST';
sheet.getCell('E6').value = 'Test project';
sheet.getCell('E7').value = '- เงินกู้ในประเทศ';
sheet.getCell('F7').value = '(12.500)';
sheet.getCell('G7').value = {formula:'1+1',result:2};
sheet.getCell('E8').value = '- เงินรายได้ กฟภ.';
sheet.getCell('F8').value = 100;
sheet.getCell('E9').value = '- ที่ดิน';
sheet.getCell('F9').value = 20;
sheet.getCell('E10').value = 'รวม';
sheet.getCell('F10').value = 107.5; // Incorrect source subtotal must be surfaced.
sheet.getCell('G10').value = 2;
const parsed = parseNineBoxExcel(book, [{id:'master-1',code:'PRJ-2569-00001'}]);
assert.equal(parsed.sheets[0].errors.length,0);
const project = parsed.sheets[0].projects[0];
assert.equal(project.masterProjectId,'master-1');
assert.equal(project.items[0].bComm,-12.5);
assert.equal(project.items[0].bInv,2);
assert.equal(project.items[0].bCommManual,true);
assert.equal(project.items.slice(0,2).reduce((n,i)=>n+i.bComm,0),87.5);
assert.equal(parsed.warnings.length,1);
sheet.getCell('A11').value='PRJ-2569-00001';
sheet.getCell('E11').value='Duplicate';
assert.match(parseNineBoxExcel(book).sheets[0].errors[0],/ซ้ำ/);
console.log('PASS: year mapping, master identity, negatives, cached formulas, subrow totals, duplicate rejection');
